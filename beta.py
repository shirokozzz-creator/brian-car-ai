import streamlit as st
import pandas as pd
import matplotlib.pyplot as plt

def render_tco_battle():
    st.title("⚔️ Naval Motors: 5年期 TCO 終極決戰矩陣")
    st.markdown("去除品牌濾鏡，直擊資產真相。本模型已量化**折舊、稅金、油資與高機率維修風險**。")

    # --- 1. 核心數據庫 ---
    data = {
        "車款": ["Prius 3", "Camry 7.5H", "Altis HV", "Prius 4", "CC HV"],
        "買入價 (CapEx)": [160000, 165000, 450000, 500000, 600000],
        "5年折舊 (沉沒)": [130000, 125000, 200000, 220000, 280000],
        "5年油資 (OPEX)": [107386, 138970, 102717, 94500, 118125],
        "5年稅金 (規費)": [59600, 112050, 59600, 59600, 59600],
        "風險準備金 (尾端風險)": [100000, 80000, 50000, 50000, 50000] # ABS總泵、大電池、底盤等
    }
    df = pd.DataFrame(data)
    
    # 計算總和
    df["5年總 TCO"] = df["5年折舊 (沉沒)"] + df["5年油資 (OPEX)"] + df["5年稅金 (規費)"] + df["風險準備金 (尾端風險)"]
    df["每月真實成本"] = df["5年總 TCO"] / 60

    # --- 2. 數據視覺化 ---
    st.subheader("📊 5年期真實持有成本結構分析")
    
    # 建立堆疊長條圖的數據格式
    chart_data = df.set_index("車款")[["5年折舊 (沉沒)", "5年油資 (OPEX)", "5年稅金 (規費)", "風險準備金 (尾端風險)"]]
    
    # 使用 Streamlit 內建圖表
    st.bar_chart(chart_data)

    # 顯示詳細數據表
    st.dataframe(
        df[["車款", "買入價 (CapEx)", "5年總 TCO", "每月真實成本"]].style.format({
            "買入價 (CapEx)": "${:,.0f}",
            "5年總 TCO": "${:,.0f}",
            "每月真實成本": "${:,.0f}"
        }),
        use_container_width=True
    )

    st.divider()

    # --- 3. 董事會智庫 (Expert Board) ---
    st.subheader("🧠 董事會智庫：資本與心智的槓桿分析")
    
    tab1, tab2, tab3 = st.tabs(["🚀 Elon Musk (物理與工程)", "🧘 Naval Ravikant (槓桿與心智)", "🐺 Warren Buffett (資本配置)"])
    
    with tab1:
        st.markdown("""
        **核心指標：第一性原理 (First Principles)**
        > 「從物理學來看，休旅車 (CC HV) 是巨大的能量浪費。增加迎風面積與車重，只為了虛榮的駕駛視野，這是低效的工程妥協。
        > **最佳解是 Prius 4。** $Cd = 0.24$ 的風阻係數，加上 TNGA 輕量化高剛性底盤，這是將能量轉換效率推向極限的傑作。Camry 7.5H？那是拖著 250kg 廢鐵在移動的過時機器。」
        """)
        
    with tab2:
        st.markdown("""
        **核心指標：心智頻寬 (Peace of Mind) 與體驗 ROI**
        > 「計算 TCO 時，不要漏算你的『精神消耗』。Prius 3 雖然帳面成本最低 ($6,616/月)，但你每天要忍受噪音，並擔憂煞車失靈的黑天鵝事件。
        > 為了升級到 Prius 4 的安靜與穩定，你每月只需多付 $452 元。用這點小錢買下未來 5 年的心智平靜，讓你在車上能專注思考商業模式，這是**極高期望值 (High EV)** 的交易。」
        """)
        
    with tab3:
        st.markdown("""
        **核心指標：護城河 (Moat) 與機會成本**
        > 「Camry 2.5L 的稅金級距是典型的**『愚蠢稅 (Stupidity Tax)』**。買入一項每年強制產生 2 萬元負現金流的資產，違背了不虧錢的第一法則。
        > 最堅固的防禦資產是 **Altis HV**，流動性極高，隨時可變現。但如果考量到工程壽命的折舊，我會用便宜的價格買入 Prius 3，並在系統崩潰前將其拋售，把價差投入 S&P 500。」
        """)

    st.divider()

    # --- 4. 紅方教練壓力測試 (Red Team Stress Test) ---
    st.subheader("🟥 紅方教練 (Red Team)：致命邏輯漏洞警告")
    st.error("""
    **您的計畫存在嚴重的倖存者偏差，以下是資產歸零的潛在路徑：**

    1.  **Prius 3 的流動性陷阱：** 您以為車價 16 萬很便宜？一旦 ABS 總泵發出連續『滋滋』聲或亮燈，這台車的市場流動性瞬間歸零。只能花 5 萬修復，或以 5 萬報廢價賤賣。**如果不編列這 10 萬元的維修呆帳準備金，您的 TCO 模型就是一張廢紙。**
    2.  **Camry 7.5H 的二手毒藥屬性：** 車商用 16.5 萬便宜賣你，是因為 2494c.c. 的稅金在台灣是二手市場的票房毒藥。您現在買得便宜，5 年後您連 4 萬塊都賣不掉。
    3.  **Corolla Cross 的消費主義陷阱 (Low EV)：** 花 60 萬買一台 TCO 成本最高 ($8,462/月)、折舊最慘重的車。除了跟風市場，這在財務與物理效率上毫無邏輯可言。
    
    **🎯 紅隊最終戰術指令：**
    監控您現有的 Prius 3，一旦 ABS 馬達作動頻率低於 60 秒，**立刻獲利了結，無縫接軌買入 Prius 4。** 將維修的尾端風險轉嫁給市場，這是唯一確保資本不被侵蝕的冷酷決策。
    """)

if __name__ == "__main__":
    render_tco_battle()
